<?php

namespace App\Models;

use App\Models\Concerns\HasAutoGeneratedNumber;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Relations\HasOne;

class Invoice extends Model
{
    use HasAutoGeneratedNumber;

    protected $attributes = [
        'source' => 'CLINICAL',
    ];

    public $incrementing = true;

    protected $keyType = 'int';

    protected $fillable = [
        'invoice_number',
        'patient_id',
        'prescription_id',
        'appointment_id',
        'invoice_date',
        'subtotal',
        'discount',
        'tax',
        'tax_percent',
        'tax_amount',
        'total',
        'grand_total',
        'paid_amount',
        'due_amount',
        'status',
        'notes',
        'source',
        'cashier_id',
        'pos_token'];

    protected static function booted(): void
    {
        static::bootHasAutoGeneratedNumber();
    }

    public function numberColumn(): string
    {
        return 'invoice_number';
    }

    public function numberPrefix(): string
    {
        return 'INV-';
    }

    protected function casts(): array
    {
        return [
            'invoice_date' => 'date',
            'subtotal' => 'decimal:2',
            'discount' => 'decimal:2',
            'tax' => 'decimal:2',
            'tax_percent' => 'decimal:2',
            'tax_amount' => 'decimal:2',
            'total' => 'decimal:2',
            'grand_total' => 'decimal:2',
            'paid_amount' => 'decimal:2',
            'due_amount' => 'decimal:2'];
    }

    public function patient(): BelongsTo
    {
        return $this->belongsTo(Patient::class);
    }

    public function prescription(): BelongsTo
    {
        return $this->belongsTo(Prescription::class);
    }

    public function appointment(): BelongsTo
    {
        return $this->belongsTo(Appointment::class);
    }

    public function items(): HasMany
    {
        return $this->hasMany(InvoiceItem::class);
    }

    public function payments(): HasMany
    {
        return $this->hasMany(Payment::class);
    }

    public function cashier(): BelongsTo
    {
        return $this->belongsTo(User::class, 'cashier_id');
    }

    public function stockMovements(): HasMany
    {
        return $this->hasMany(PharmacyStockMovement::class);
    }

    public function pharmacyRefund(): HasOne
    {
        return $this->hasOne(PharmacyRefund::class);
    }

    public function getGrandTotalAttribute(): float
    {
        return (float) ($this->attributes['grand_total'] ?? $this->attributes['total'] ?? 0);
    }

    public function setGrandTotalAttribute(float|int|string $value): void
    {
        $this->attributes['grand_total'] = (string) round((float) $value, 2);
        $this->attributes['total'] = $this->attributes['grand_total'];
    }
}
