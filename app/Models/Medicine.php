<?php

namespace App\Models;

use App\Models\Concerns\HasAutoGeneratedNumber;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;

class Medicine extends Model
{
    use HasAutoGeneratedNumber;

    public $incrementing = true;

    protected $keyType = 'int';

    protected $fillable = [
        'medicine_code',
        'name',
        'generic_name',
        'category',
        'manufacturer',
        'dosage_form',
        'strength',
        'quantity',
        'unit_price',
        'expiry_date',
        'status'];

    protected static function booted(): void
    {
        static::bootHasAutoGeneratedNumber();
    }

    public function numberColumn(): string
    {
        return 'medicine_code';
    }

    public function numberPrefix(): string
    {
        return 'MED-';
    }

    public function getMedicineNumberAttribute(): ?string
    {
        return $this->medicine_code;
    }

    protected function casts(): array
    {
        return [
            'expiry_date' => 'date',
            'unit_price' => 'decimal:2'];
    }

    public function prescriptions(): BelongsToMany
    {
        return $this->belongsToMany(Prescription::class)->withPivot([
            'dosage',
            'frequency',
            'duration',
            'quantity',
            'instructions',
        ]
        )->withTimestamps();
    }

    public function stockBatches(): HasMany
    {
        return $this->hasMany(PharmacyStockBatch::class);
    }

    public function stockMovements(): HasMany
    {
        return $this->hasMany(PharmacyStockMovement::class);
    }
}
