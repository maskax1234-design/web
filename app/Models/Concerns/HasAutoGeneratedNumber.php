<?php

namespace App\Models\Concerns;

use Illuminate\Support\Facades\DB;

trait HasAutoGeneratedNumber
{
    protected static function bootHasAutoGeneratedNumber(): void
    {
        static::creating(function (self $model): void {
            $column = $model->numberColumn();

            if (empty($column) || ! empty($model->getAttribute($column))) {
                return;
            }

            $model->setAttribute($column, DB::transaction(function () use ($column, $model): string {
                $maxValue = static::query()
                    ->whereNotNull($column)
                    ->get()
                    ->map(function ($record) use ($column, $model): int {
                        $value = (string) $record->{$column};

                        if (! str_starts_with($value, $model->numberPrefix())) {
                            return 0;
                        }

                        preg_match('/(\d+)$/', $value, $matches);

                        return (int) ($matches[1] ?? 0);
                    })
                    ->max() ?? 0;

                return $model->numberPrefix().str_pad((string) ($maxValue + 1), 4, '0', STR_PAD_LEFT);
            }));
        });
    }

    abstract public function numberColumn(): string;

    abstract public function numberPrefix(): string;
}