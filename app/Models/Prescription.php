<?php

namespace App\Models;

use App\Models\Concerns\HasAutoGeneratedNumber;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Relations\HasOne;

class Prescription extends Model
{
    use HasAutoGeneratedNumber;

    public $incrementing = true;

    protected $keyType = 'int';

    protected $fillable = [
        'prescription_number',
        'patient_id',
        'doctor_id',
        'appointment_id',
        'prescription_date',
        'instructions',
        'status'];

    protected static function booted(): void
    {
        static::bootHasAutoGeneratedNumber();
    }

    public function numberColumn(): string
    {
        return 'prescription_number';
    }

    public function numberPrefix(): string
    {
        return 'PRE-';
    }

    protected function casts(): array
    {
        return [
            'prescription_date' => 'date'];
    }

    public function patient(): BelongsTo
    {
        return $this->belongsTo(Patient::class);
    }

    public function doctor(): BelongsTo
    {
        return $this->belongsTo(Doctor::class);
    }

    public function appointment(): BelongsTo
    {
        return $this->belongsTo(Appointment::class);
    }

    public function medicines(): BelongsToMany
    {
        return $this->belongsToMany(Medicine::class)->withPivot([
            'dosage',
            'frequency',
            'duration',
            'quantity',
            'instructions',
            'unit_price',
            'total',
        ])
            ->withTimestamps();
    }

    public function prescriptionItems(): HasMany
    {
        return $this->hasMany(PrescriptionItem::class);
    }

    public function invoice(): HasOne
    {
        return $this->hasOne(Invoice::class);
    }
}
